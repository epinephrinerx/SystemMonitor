/// Thai and English text. The keys and most of the wording follow the Windows
/// build's `I18n.cs`; where macOS calls a thing something else (the menu bar,
/// Storage settings) the Mac wording is used.
public struct Strings: Sendable {
    public let lang: String

    public init(_ lang: String) {
        self.lang = lang == "th" ? "th" : "en"
    }

    /// Falls back to English, then to the key itself, so a missing string is
    /// visible rather than blank.
    public func callAsFunction(_ key: String, _ args: String...) -> String {
        var text = (lang == "th" ? Strings.th[key] : nil) ?? Strings.en[key] ?? key
        for (i, arg) in args.enumerated() {
            text = text.replacingOccurrences(of: "{\(i)}", with: arg)
        }
        return text
    }

